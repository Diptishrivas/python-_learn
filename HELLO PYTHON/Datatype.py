# data types in python
# 1. Integer
age =22
print(type(age))

# 2. Float
height = 5.6
print(type(height))

# 3. String
name = "Deep"
print(type(name))

# 4. Boolean
is_student = 'true'
print(type(is_student))

# 5.list
fruits = ["apple", "banana", "cherry"]
print(type(fruits))

# #tuple

numbers = (1, 2, 3, 4, 5)
print(type(numbers))

# 6.sets
colors = {"red", "green", "blue"}
print(type(colors))

# 7. Dictionary
student = {
    "name": "dipti",
    "surname": "shrivas",
    "age": 22
}
print(type(student))

